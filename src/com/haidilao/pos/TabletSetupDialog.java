    /** Tìm máy chủ bằng UDP broadcast trên luồng nền, xong thì điền danh sách bàn máy chủ gửi về */
    private void search() {
        btnStart.setEnabled(false);
        btnSearchAgain.setEnabled(false);
        lblServer.setForeground(com.haidilao.pos.ui.Theme.BLUE);
        lblServer.setText("Đang tìm máy chủ trong mạng Wi-Fi...");
        new javax.swing.SwingWorker<com.haidilao.pos.client.ServerLocator.Found, Void>() {
            @Override
            protected com.haidilao.pos.client.ServerLocator.Found doInBackground() {
                return com.haidilao.pos.client.ServerLocator.discover(2500);
            }

            @Override
            protected void done() {
                btnSearchAgain.setEnabled(true);
                com.haidilao.pos.client.ServerLocator.Found found = null;
                try {
                    found = get();
                } catch (Exception ignored) {}
                showResult(found);
            }
        }.execute();
    }

    private void showResult(com.haidilao.pos.client.ServerLocator.Found found) {
        tableIds.clear();
        cboTable.removeAllItems();
        if (found == null) {
            lblServer.setForeground(com.haidilao.pos.ui.Theme.RED);
            lblServer.setText("Chưa tìm thấy máy chủ. Bấm \"Tìm lại\" sau khi bật máy chủ.");
            return;
        }
        lblServer.setForeground(com.haidilao.pos.ui.Theme.GREEN);
        lblServer.setText("Đã tìm thấy: " + (found.restaurantName.isEmpty() ? "Máy chủ" : found.restaurantName) + "  (" + found.host + ")");
        String saved = com.haidilao.pos.client.LocalConfig.get(com.haidilao.pos.client.LocalConfig.TABLET_TABLE, "");
        for (String[] t : found.tables) {
            tableIds.add(t[0]);
            cboTable.addItem(t[1] + "   (" + t[0] + ")");
            if (t[0].equals(saved)) cboTable.setSelectedIndex(tableIds.size() - 1);
        }
        btnStart.setEnabled(!tableIds.isEmpty());
        if (tableIds.isEmpty()) {
            lblServer.setText(lblServer.getText() + " · chưa có bàn nào, nhờ quản lý thêm bàn.");
        }
    }

