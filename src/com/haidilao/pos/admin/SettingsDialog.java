    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        JTextField[] fields = {txtRestaurantName, txtBankName, txtBankAccount, txtBankOwner};
        for (JTextField f : fields) {
            if (f.getText().trim().isEmpty() || f.getText().trim().length() > 120) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập đủ các ô (tối đa 120 ký tự).", "Cài đặt", JOptionPane.WARNING_MESSAGE);
                return;
            }
        }
        SettingsDao.set(SettingsDao.RESTAURANT_NAME, txtRestaurantName.getText());
        SettingsDao.set(SettingsDao.BANK_NAME, txtBankName.getText());
        SettingsDao.set(SettingsDao.BANK_ACCOUNT, txtBankAccount.getText());
        SettingsDao.set(SettingsDao.BANK_OWNER, txtBankOwner.getText());
        JOptionPane.showMessageDialog(this, "Đã lưu cài đặt.");
        dispose();
    }//GEN-LAST:event_btnSaveActionPerformed

