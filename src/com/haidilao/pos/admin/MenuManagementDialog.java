    private void loadData() {
        tableModel.setRowCount(0);
        imageById.clear();
        List<MenuItem> items = DatabaseManager.getAllMenuItemsAdmin();
        for (MenuItem item : items) {
            imageById.put(item.getItemId(), item.getImageData());
            tableModel.addRow(new Object[]{
                    item.getItemId(),
                    item.getCategory(),
                    item.getItemName(),
                    new DecimalFormat("#,###").format(item.getPrice()),
                    item.getStatus()
            });
        }

        // Tải danh sách phân loại hiện có vào cboCategory
        List<String> cats = DatabaseManager.getAllCategories();
        cboCategory.removeAllItems();
        for (String c : cats) {
            cboCategory.addItem(c);
        }
        if (cboCategory.getItemCount() == 0) {
            cboCategory.addItem("1. Nước Lẩu");
            cboCategory.addItem("2. Thịt Bò & Cừu");
            cboCategory.addItem("3. Hải Sản & Viên Thả");
            cboCategory.addItem("4. Rau Củ & Nấm");
        }
        clearForm();
    }

    private void populateFormFromRow(int row) {
        txtItemId.setText(tableModel.getValueAt(row, 0).toString());
        String cat = tableModel.getValueAt(row, 1).toString();
        cboCategory.setSelectedItem(cat);
        txtItemName.setText(tableModel.getValueAt(row, 2).toString());

        String priceStr = tableModel.getValueAt(row, 3).toString().replace(".", "").replace(",", "").trim();
        txtPrice.setText(priceStr);

        String status = tableModel.getValueAt(row, 4).toString();
        cboStatus.setSelectedItem(status);

        int itemId = Integer.parseInt(tableModel.getValueAt(row, 0).toString());
        currentImage = imageById.get(itemId);
        imageChanged = false;
        showImagePreview(currentImage);
    }

    private void clearForm() {
        txtItemId.setText("");
        txtItemName.setText("");
        txtPrice.setText("");
        cboStatus.setSelectedIndex(0);
        currentImage = null;
        imageChanged = false;
        showImagePreview(null);
        tblMenuItems.clearSelection();
    }

    /**
     * Mở hộp thoại chọn file ảnh, thu nhỏ rồi hiện lên khung xem trước (chưa lưu MySQL cho đến khi bấm Thêm / Lưu)
     */
    private void chooseImage() {
        JFileChooser chooser = new JFileChooser(lastImageDir);
        chooser.setDialogTitle("Chọn ảnh món ăn");
        chooser.setFileFilter(new FileNameExtensionFilter("Ảnh (jpg, png, gif, bmp)", "jpg", "jpeg", "png", "gif", "bmp"));
        if (chooser.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) {
            return;
        }

        File file = chooser.getSelectedFile();
        lastImageDir = file.getParentFile();
        try {
            currentImage = ImageUtil.createThumbnail(file); // thu nhỏ còn tối đa 400x300 để gửi qua mạng nhanh
            imageChanged = true;
            showImagePreview(currentImage);
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Không đọc được ảnh: " + ex.getMessage(), "Lỗi ảnh", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void removeImage() {
        if (currentImage == null) return;
        currentImage = null;
        imageChanged = true;
        showImagePreview(null);
    }

    private void showImagePreview(byte[] imageData) {
        ImageIcon icon = ImageUtil.toIcon(imageData);
        lblImagePreview.setIcon(icon);
        lblImagePreview.setText(icon == null ? "Chưa có ảnh" : "");
    }

    private void onAddDish() {
        String name = txtItemName.getText().trim();
        String cat = (cboCategory.getSelectedItem() != null) ? cboCategory.getSelectedItem().toString().trim() : "";
        String priceText = txtPrice.getText().trim().replace(".", "").replace(",", "");
        String status = (String) cboStatus.getSelectedItem();

        if (name.isEmpty() || cat.isEmpty() || priceText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ: Tên món, Thể loại và Đơn giá!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        long price;
        try {
            price = Long.parseLong(priceText);
            if (price <= 0) throw new NumberFormatException();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Đơn giá phải là số dương hợp lệ!", "Lỗi định dạng", JOptionPane.ERROR_MESSAGE);
            return;
        }

        boolean success = DatabaseManager.addMenuItem(cat, name, price, status, currentImage);
        if (success) {
            notifyServerAndClients("[MENU-ADD] Đã thêm món mới: [" + name + "] (" + cat + " - " + price + " VNĐ)");
            JOptionPane.showMessageDialog(this, "Thêm món ăn mới vào cơ sở dữ liệu thành công!");
            loadData();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm món ăn thất bại! Vui lòng kiểm tra kết nối MySQL.", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void onUpdateDish() {
        String idText = txtItemId.getText().trim();
        if (idText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một món ăn trong bảng danh sách để cập nhật!", "Chưa chọn món", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int itemId = Integer.parseInt(idText);
        String name = txtItemName.getText().trim();
        String cat = (cboCategory.getSelectedItem() != null) ? cboCategory.getSelectedItem().toString().trim() : "";
        String priceText = txtPrice.getText().trim().replace(".", "").replace(",", "");
        String status = (String) cboStatus.getSelectedItem();

        if (name.isEmpty() || cat.isEmpty() || priceText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng không để trống thông tin món ăn!", "Thiếu thông tin", JOptionPane.WARNING_MESSAGE);
            return;
        }

        long price;
        try {
            price = Long.parseLong(priceText);
            if (price <= 0) throw new NumberFormatException();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Đơn giá phải là số hợp lệ!", "Lỗi định dạng", JOptionPane.ERROR_MESSAGE);
            return;
        }

        boolean success = DatabaseManager.updateMenuItem(itemId, cat, name, price, status);
        if (success && imageChanged) {
            success = DatabaseManager.updateMenuItemImage(itemId, currentImage);
        }
        if (success) {
            notifyServerAndClients("[MENU-UPDATE] Đã cập nhật món #" + itemId + ": [" + name + "] (" + status + ")");
            JOptionPane.showMessageDialog(this, "Cập nhật thông tin món ăn thành công!");
            loadData();
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void onDeleteDish() {
        String idText = txtItemId.getText().trim();
        if (idText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn món cần xóa trong bảng!", "Chưa chọn món", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int itemId = Integer.parseInt(idText);
        String name = txtItemName.getText().trim();

        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc muốn xóa món ăn [" + name + "] (Mã ID: " + itemId + ") khỏi cơ sở dữ liệu?",
                "Xác nhận xóa món",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);

        if (confirm == JOptionPane.YES_OPTION) {
            boolean success = DatabaseManager.deleteMenuItem(itemId);
            if (success) {
                notifyServerAndClients("[MENU-DELETE] Đã xóa món #" + itemId + ": [" + name + "] khỏi hệ thống.");
                JOptionPane.showMessageDialog(this, "Đã xóa món ăn thành công!");
                loadData();
            } else {
                JOptionPane.showMessageDialog(this, "Xóa món thất bại!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

    private void notifyServerAndClients(String logMsg) {
        if (posServer != null) {
            posServer.log(logMsg);
            posServer.broadcastToTablets("MENU_UPDATED|Cập nhật thực đơn mới");
        }
    }

