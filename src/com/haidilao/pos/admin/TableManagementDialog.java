    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        DiningTable t = readForm();
        if (t == null) return;
        if (TableDao.getTable(t.getTableId()) != null) {
            JOptionPane.showMessageDialog(this, "Mã bàn " + t.getTableId() + " đã tồn tại.", "Trùng mã bàn", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (TableDao.addTable(t)) afterChange("Thêm bàn " + t.getTableName() + " (" + t.getTableId() + ")");
        else JOptionPane.showMessageDialog(this, "Không thêm được bàn.", "Lỗi", JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        DiningTable t = readForm();
        if (t == null) return;
        if (TableDao.updateTable(t)) afterChange("Sửa bàn " + t.getTableName());
        else JOptionPane.showMessageDialog(this, "Không lưu được thay đổi.", "Lỗi", JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String id = txtTableId.getText().trim();
        if (TableDao.hasSessions(id)) {
            JOptionPane.showMessageDialog(this, "Bàn này đã có lịch sử phục vụ nên không xóa được (giữ số liệu thống kê).\nCó thể đổi tên hoặc khu vực thay vì xóa.",
                    "Không xóa được", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "Xóa bàn " + id + "?", "Xóa bàn", JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) return;
        if (TableDao.deleteTable(id)) afterChange("Xóa bàn " + id);
        else JOptionPane.showMessageDialog(this, "Không xóa được bàn.", "Lỗi", JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_btnDeleteActionPerformed

