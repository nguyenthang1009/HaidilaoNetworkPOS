    private void loadTables() {
        model.setRowCount(0);
        int seats = 0;
        Map<String, Integer> byArea = new TreeMap<>();
        for (DiningTable t : TableDao.getAllTables()) {
            model.addRow(new Object[]{t.getTableId(), t.getTableName(), t.getCapacity(), t.getArea(), t.getStatus()});
            seats += t.getCapacity();
            byArea.merge(t.getArea(), 1, Integer::sum);
        }
        StringBuilder sb = new StringBuilder("Tổng: " + model.getRowCount() + " bàn · " + seats + " ghế");
        for (Map.Entry<String, Integer> e : byArea.entrySet()) sb.append("  ·  ").append(e.getKey()).append(": ").append(e.getValue());
        lblSummary.setText(sb.toString());
    }

    private void showSelected() {
        int row = tblTables.getSelectedRow();
        if (row < 0) return;
        txtTableId.setText(String.valueOf(model.getValueAt(row, 0)));
        txtTableId.setEditable(false);
        txtTableName.setText(String.valueOf(model.getValueAt(row, 1)));
        spnCapacity.setValue(model.getValueAt(row, 2));
        cboArea.setSelectedItem(model.getValueAt(row, 3));
        cboStatus.setSelectedItem(model.getValueAt(row, 4));
        btnAdd.setEnabled(false);
        btnUpdate.setEnabled(true);
        btnDelete.setEnabled(true);
    }

    private void clearForm() {
        tblTables.clearSelection();
        txtTableId.setEditable(true);
        txtTableId.setText("Tablet_Ban" + (model.getRowCount() + 1));
        txtTableName.setText("Bàn " + (model.getRowCount() + 1));
        spnCapacity.setValue(4);
        cboArea.setSelectedIndex(0);
        cboStatus.setSelectedIndex(0);
        btnAdd.setEnabled(true);
        btnUpdate.setEnabled(false);
        btnDelete.setEnabled(false);
    }

    /** Đọc form, trả về null nếu dữ liệu sai (đã báo lỗi) */
    private DiningTable readForm() {
        String id = txtTableId.getText().trim();
        String name = txtTableName.getText().trim();
        String area = String.valueOf(cboArea.getSelectedItem()).trim();
        if (!id.matches("[A-Za-z0-9_\\-]{1,30}")) {
            JOptionPane.showMessageDialog(this, "Mã bàn chỉ gồm chữ không dấu, số, _ và - (tối đa 30 ký tự).", "Dữ liệu chưa hợp lệ", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        if (name.isEmpty() || name.length() > 50 || area.isEmpty() || area.length() > 50) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập tên bàn và khu vực (tối đa 50 ký tự).", "Dữ liệu chưa hợp lệ", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        return new DiningTable(id, name, (Integer) spnCapacity.getValue(), area, String.valueOf(cboStatus.getSelectedItem()), 0);
    }

    private void afterChange(String message) {
        loadTables();
        clearForm();
        if (posServer != null) {
            posServer.broadcastTablesChanged();
            posServer.log("[ADMIN] " + message);
        }
    }

