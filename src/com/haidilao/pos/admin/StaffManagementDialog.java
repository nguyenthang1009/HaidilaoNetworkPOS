    private void loadStaff() {
        model.setRowCount(0);
        staffList.clear();
        Map<String, Integer> byRole = new TreeMap<>();
        for (Staff s : StaffDao.getAllStaff()) {
            staffList.add(s);
            model.addRow(new Object[]{s.getStaffId(), s.getUsername(), s.getFullName(), s.getRole(), s.getPhone() == null ? "" : s.getPhone(),
                    s.isActive() ? "Đang làm" : "Đã nghỉ"});
            if (s.isActive()) byRole.merge(s.getRole(), 1, Integer::sum);
        }
        StringBuilder sb = new StringBuilder("Đang làm việc:");
        for (Map.Entry<String, Integer> e : byRole.entrySet()) sb.append("  ").append(e.getKey()).append(" ").append(e.getValue());
        lblSummary.setText(sb.toString());
    }

    private Staff selected() {
        int row = tblStaff.getSelectedRow();
        return row < 0 ? null : staffList.get(tblStaff.convertRowIndexToModel(row));
    }

    private void showSelected() {
        Staff s = selected();
        if (s == null) return;
        txtStaffId.setText(String.valueOf(s.getStaffId()));
        txtUsername.setText(s.getUsername());
        txtUsername.setEditable(false);
        txtPassword.setText("");
        txtFullName.setText(s.getFullName());
        cboRole.setSelectedItem(s.getRole());
        txtPhone.setText(s.getPhone() == null ? "" : s.getPhone());
        chkActive.setSelected(s.isActive());
        btnAdd.setEnabled(false);
        btnUpdate.setEnabled(true);
        btnDelete.setEnabled(true);
    }

    private void clearForm() {
        tblStaff.clearSelection();
        txtStaffId.setText("(tự cấp)");
        txtUsername.setText("");
        txtUsername.setEditable(true);
        txtPassword.setText("");
        txtFullName.setText("");
        cboRole.setSelectedItem(Staff.ROLE_WAITER);
        txtPhone.setText("");
        chkActive.setSelected(true);
        btnAdd.setEnabled(true);
        btnUpdate.setEnabled(false);
        btnDelete.setEnabled(false);
    }

    private boolean validateCommon() {
        String name = txtFullName.getText().trim();
        String phone = txtPhone.getText().trim();
        if (name.isEmpty() || name.length() > 80) return warn("Vui lòng nhập họ tên (tối đa 80 ký tự).");
        if (!phone.isEmpty() && !phone.matches("[0-9 +.\\-]{6,20}")) return warn("Số điện thoại không hợp lệ.");
        return true;
    }

    private boolean warn(String msg) {
        JOptionPane.showMessageDialog(this, msg, "Dữ liệu chưa hợp lệ", JOptionPane.WARNING_MESSAGE);
        return false;
    }

    /** Không được làm mất quản lý cuối cùng (sẽ không ai vào được máy chủ) */
    private boolean keepsAManager(Staff s, String newRole, boolean newActive) {
        boolean wasActiveManager = s.isActive() && Staff.ROLE_MANAGER.equals(s.getRole());
        boolean staysActiveManager = newActive && Staff.ROLE_MANAGER.equals(newRole);
        return !(wasActiveManager && !staysActiveManager && StaffDao.countActiveManagers() <= 1);
    }

