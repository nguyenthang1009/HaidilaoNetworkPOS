    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String user = txtUsername.getText().trim();
        String pass = new String(txtPassword.getPassword());
        if (!user.matches("[A-Za-z0-9_.]{3,30}")) {
            warn("Tài khoản 3-30 ký tự, chỉ gồm chữ không dấu, số, dấu chấm và gạch dưới.");
            return;
        }
        if (pass.length() < 6) {
            warn("Mật khẩu tối thiểu 6 ký tự.");
            return;
        }
        if (!validateCommon()) return;
        if (StaffDao.usernameExists(user)) {
            warn("Tài khoản " + user + " đã tồn tại.");
            return;
        }
        if (StaffDao.addStaff(user, pass, txtFullName.getText().trim(), String.valueOf(cboRole.getSelectedItem()), txtPhone.getText().trim(), chkActive.isSelected())) {
            loadStaff();
            clearForm();
        } else {
            JOptionPane.showMessageDialog(this, "Không thêm được nhân viên.", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        Staff s = selected();
        if (s == null || !validateCommon()) return;
        String pass = new String(txtPassword.getPassword());
        if (!pass.isEmpty() && pass.length() < 6) {
            warn("Mật khẩu mới tối thiểu 6 ký tự.");
            return;
        }
        String role = String.valueOf(cboRole.getSelectedItem());
        if (!keepsAManager(s, role, chkActive.isSelected())) {
            warn("Đây là tài khoản Quản lý cuối cùng, không thể đổi vai trò hoặc cho nghỉ.");
            return;
        }
        if (StaffDao.updateStaff(s.getStaffId(), txtFullName.getText().trim(), role, txtPhone.getText().trim(), chkActive.isSelected(), pass)) {
            loadStaff();
            clearForm();
        } else {
            JOptionPane.showMessageDialog(this, "Không lưu được thay đổi.", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        Staff s = selected();
        if (s == null) return;
        if (currentManager != null && s.getStaffId() == currentManager.getStaffId()) {
            warn("Không thể xóa tài khoản đang đăng nhập.");
            return;
        }
        if (!keepsAManager(s, "", false)) {
            warn("Đây là tài khoản Quản lý cuối cùng, không thể xóa.");
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "Xóa nhân viên " + s.getFullName() + "?\nCác bàn từng do người này phục vụ vẫn được giữ.",
                "Xóa nhân viên", JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) return;
        if (StaffDao.deleteStaff(s.getStaffId())) {
            loadStaff();
            clearForm();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

