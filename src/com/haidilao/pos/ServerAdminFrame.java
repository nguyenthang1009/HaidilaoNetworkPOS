    private void initCustomLogic() {
        setLocationRelativeTo(null);
        deviceTableModel = (DefaultTableModel) tblActiveDevices.getModel();
        posServer = new PosServer(ProtocolConstants.SERVER_PORT);
        posServer.setListener(this);

        // Kiểm tra kết nối MySQL Laragon
        checkDatabase();
    }

    private void checkDatabase() {
        boolean ok = DatabaseManager.testConnection();
        if (ok) {
            lblDbStatus.setText("● MYSQL (3306): KẾT NỐI OK");
            lblDbStatus.setForeground(new Color(46, 204, 113));
            DatabaseManager.ensureMenuImageColumn(); // database cũ chưa có cột ảnh món ăn thì tự thêm
            DatabaseManager.ensureSecurityLogTable(); // chưa có bảng nhật ký an ninh thì tự tạo
            refreshRevenue();
            logAcl("[MYSQL-3306] Đã kết nối cơ sở dữ liệu haidilao_pos_db trên Laragon thành công.");
        } else {
            lblDbStatus.setText("● MYSQL (3306): MẤT KẾT NỐI");
            lblDbStatus.setForeground(new Color(231, 76, 60));
            logAcl("[MYSQL-WARN] Không thể kết nối MySQL 3306. Vui lòng kiểm tra Laragon!");
        }
    }

    private void refreshRevenue() {
        long rev = DatabaseManager.getTotalRevenue();
        String formatted = new DecimalFormat("#,### VNĐ").format(rev);
        lblRevenue.setText("DOANH THU: " + formatted);
    }

    private void logAcl(String msg) {
        SwingUtilities.invokeLater(() -> {
            txtAclLog.append(msg + "\n");
            txtAclLog.setCaretPosition(txtAclLog.getDocument().getLength());
        });
    }

    // --- ServerEventListener Callbacks ---
    @Override
    public void onLog(String message) {
        logAcl(message);
    }

    @Override
    public void onServerStarted(int port) {
        SwingUtilities.invokeLater(() -> {
            lblSocketStatus.setText("● TCP (8888): ĐANG MỞ");
            lblSocketStatus.setForeground(new Color(46, 204, 113));
            btnStartServer.setEnabled(false);
            btnStartServer.setText("SERVER ĐANG CHẠY");
        });
    }

    @Override
    public void onServerStopped() {
        SwingUtilities.invokeLater(() -> {
            lblSocketStatus.setText("● TCP (8888): TẮT");
            lblSocketStatus.setForeground(new Color(231, 76, 60));
            btnStartServer.setEnabled(true);
            btnStartServer.setText("KHỞI ĐỘNG SERVER (8888)");
            deviceTableModel.setRowCount(0);
        });
    }

    @Override
    public void onDeviceConnected(String deviceId, String vlan, String ip, String mac, String status) {
        SwingUtilities.invokeLater(() -> {
            // Xóa dòng cũ nếu có
            for (int i = 0; i < deviceTableModel.getRowCount(); i++) {
                if (deviceTableModel.getValueAt(i, 0).equals(deviceId)) {
                    deviceTableModel.removeRow(i);
                    break;
                }
            }
            deviceTableModel.addRow(new Object[]{deviceId, vlan, ip, mac, status});
        });
    }

    @Override
    public void onDeviceDisconnected(String deviceId) {
        SwingUtilities.invokeLater(() -> {
            for (int i = 0; i < deviceTableModel.getRowCount(); i++) {
                if (deviceTableModel.getValueAt(i, 0).equals(deviceId)) {
                    deviceTableModel.removeRow(i);
                    break;
                }
            }
        });
    }

    @Override
    public void onRevenueUpdated(long totalRevenue) {
        SwingUtilities.invokeLater(() -> {
            String formatted = new DecimalFormat("#,### VNĐ").format(totalRevenue);
            lblRevenue.setText("DOANH THU: " + formatted);
        });
    }

