    private void btnShutdownPortActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnShutdownPortActionPerformed
        // TODO add your handling code here:
        int row = tblActiveDevices.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 thiết bị trong danh sách để khóa cổng!", "Thông báo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String devId = (String) deviceTableModel.getValueAt(row, 0);
        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc muốn kích hoạt Port-Security Shutdown (Err-Disable) với thiết bị: " + devId + "?",
                "Xác nhận khóa cổng mạng",
                JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);

        if (confirm == JOptionPane.YES_OPTION) {
            boolean success = posServer.shutdownDevice(devId);
            if (success) {
                deviceTableModel.removeRow(row);
                JOptionPane.showMessageDialog(this, "Đã khóa cổng Switch và ngắt kết nối thiết bị [" + devId + "] thành công!");
            } else {
                JOptionPane.showMessageDialog(this, "Không tìm thấy phiên kết nối của thiết bị: " + devId);
            }
        }
    }//GEN-LAST:event_btnShutdownPortActionPerformed

    private void btnRestorePortActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRestorePortActionPerformed
        // TODO add your handling code here:
        // Chỉ liệt kê các thiết bị đang thực sự bị khóa (ERR_DISABLE) trong MySQL
        java.util.List<String> locked = new java.util.ArrayList<>();
        for (com.haidilao.pos.model.NetworkDevice d : DatabaseManager.getAllNetworkDevices()) {
            if ("ERR_DISABLE".equalsIgnoreCase(d.getSecurityStatus())) {
                locked.add(d.getDeviceId());
            }
        }
        if (locked.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Hiện không có thiết bị nào đang bị khóa cổng.", "Phục hồi cổng Switch", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        locked.add("TẤT CẢ THIẾT BỊ");

        String picked = (String) JOptionPane.showInputDialog(this,
                "Chọn thiết bị cần phục hồi cổng Switch (no shutdown):",
                "Phục hồi cổng Switch Port-Security",
                JOptionPane.QUESTION_MESSAGE, null, locked.toArray(new String[0]), locked.get(0));

        if (picked != null) {
            if ("TẤT CẢ THIẾT BỊ".equals(picked)) {
                posServer.restoreAllPorts();
                JOptionPane.showMessageDialog(this, "Đã mở khóa (no shutdown) cho TẤT CẢ thiết bị!\nMở lại ứng dụng trên các thiết bị đó để kết nối.");
            } else {
                posServer.unlockDevice(picked);
                JOptionPane.showMessageDialog(this, "Đã mở khóa cổng (no shutdown) cho: " + picked + ".\nMở lại ứng dụng trên thiết bị đó để kết nối.");
            }
        }
    }//GEN-LAST:event_btnRestorePortActionPerformed

